// Bakes the metrics font (see src/metricsFont.ts) from the balloon model into
// src/metricsFontData.ts: a blank font whose letters are as wide as their
// balloons (less the tracking overlap), so the page has it before three.js
// and the model load. Run by the build; run it by hand after changing the
// model, TRACKING or the font's metrics.
import opentype from "opentype.js";
import { bakeGlyphs, glyphLoader } from "../src/glyphs";

/** Overlap between neighbours as a share of a letter's width: letters are
 *  packed tighter than their colliders, so they squeeze and jostle. */
const TRACKING = -0.03;
/** Line height (in em) that fits a row of balloons. */
const LINE_HEIGHT = 1.08;
/** Space between words, in em. */
const SPACE = 0.8;
const EM = 1000;
// OS/2 fsSelection bits.
const REGULAR = 1 << 6;
const USE_TYPO_METRICS = 1 << 7;

const model = await Bun.file(new URL("../src/assets/alphabet.glb", import.meta.url)).arrayBuffer();
const { glyphs, glyphHeight } = bakeGlyphs((await glyphLoader().parseAsync(model, "")).scene);

// One em is a balloon's height. The content box (ascent to descent) is
// centred on the baseline, so a character's box centre is where its balloon
// centre goes. Lowercase is drawn as the same balloons.
const blank = (name: string, unicode: number | undefined, advanceWidth: number) =>
  new opentype.Glyph({ name, unicode, advanceWidth, path: new opentype.Path() });
const list = [blank(".notdef", undefined, SPACE * EM), blank("space", 32, SPACE * EM)];
for (const [letter, { width }] of glyphs) {
  const advance = Math.round(((width * (1 + TRACKING)) / glyphHeight) * EM);
  list.push(blank(letter, letter.charCodeAt(0), advance), blank(letter.toLowerCase(), letter.toLowerCase().charCodeAt(0), advance));
}
const half = (LINE_HEIGHT / 2) * EM;
const font = new opentype.Font({ familyName: "BalloonMetrics", styleName: "Regular", unitsPerEm: EM, ascender: half, descender: -half, glyphs: list });
// The glyphs are blank, so the Windows metrics (derived from their outlines)
// would come out zero and browsers pick some other "normal" line height. Set
// them, and prefer the typo metrics, so line-height: normal is LINE_HEIGHT
// everywhere (give or take browsers rounding it). (Merged into the generated
// OS/2 table; the typings want a whole one.)
Object.assign(font.tables, { os2: { usWinAscent: half, usWinDescent: half, fsSelection: REGULAR | USE_TYPO_METRICS } });

const out = Bun.file(new URL("../src/metricsFontData.ts", import.meta.url));
const source = `// Generated by scripts/font.ts from the balloon model: the metrics font, base64.\nexport default "${Buffer.from(font.toArrayBuffer()).toString("base64")}";\n`;
// Only when it changed, so a watching build isn't set off again by its own output.
if (!(await out.exists()) || (await out.text()) !== source) await Bun.write(out, source);
